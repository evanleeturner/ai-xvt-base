/// A panic traps, as clang's undefined-behavior build does: `ud2`, which
/// Windows raises as an illegal instruction, so the checker reads it the same.
#[panic_handler]
#[expect(unsafe_code, reason = "the trap is one instruction of inline assembly")]
fn panic(_info: &core::panic::PanicInfo<'_>) -> ! {
    // SAFETY: ud2 raises the illegal-instruction exception and nothing after
    // it runs; the probe catches the exception.
    unsafe { core::arch::asm!("ud2", options(noreturn, nomem, nostack)) }
}
